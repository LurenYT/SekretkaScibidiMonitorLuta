const rowsEl = document.querySelector('#rows');
const statusEl = document.querySelector('#status');
const metaEl = document.querySelector('#meta');
const emptyEl = document.querySelector('#empty');
const tabs = [...document.querySelectorAll('.tab')];

let data = null;
let activeTab = 'survivors';

function escapeHtml(value) {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#039;');
}

function playerHtml(player) {
  const username = escapeHtml(player.username || `User ${player.userId}`);
  const userId = encodeURIComponent(player.userId);
  return `<a class="player" href="https://www.roblox.com/users/${userId}/profile" target="_blank" rel="noreferrer">${username}</a>`;
}

function render() {
  if (!data) return;
  const rows = data[activeTab] || [];

  rowsEl.innerHTML = rows.map((row, index) => {
    const players = row.players?.length
      ? `<div class="players">${row.players.map(playerHtml).join('')}</div>`
      : '<span class="no-player">—</span>';

    return `
      <tr>
        <td>${index + 1}</td>
        <td class="character">${escapeHtml(row.character)}</td>
        <td><span class="level ${row.level === 0 ? 'zero' : ''}">${escapeHtml(row.level)}</span></td>
        <td>${players}</td>
      </tr>
    `;
  }).join('');

  emptyEl.classList.toggle('hidden', rows.length > 0);
}

for (const tab of tabs) {
  tab.addEventListener('click', () => {
    activeTab = tab.dataset.tab;
    for (const item of tabs) item.classList.toggle('active', item === tab);
    render();
  });
}

async function load() {
  statusEl.textContent = 'Загрузка…';
  statusEl.classList.remove('error');

  try {
    // Relative path is important: GitHub Pages usually serves project sites at /repo-name/.
    const response = await fetch(`./data/leaderboard.json?t=${Date.now()}`, { cache: 'no-store' });
    const body = await response.json();
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    if (body.error) throw new Error(body.error);

    data = body;
    render();

    const generated = body.generatedAt ? new Date(body.generatedAt) : null;
    const validDate = generated && !Number.isNaN(generated.getTime());
    statusEl.textContent = validDate ? 'Актуально' : 'Нет обновления';
    statusEl.classList.toggle('error', !validDate);
    metaEl.textContent = validDate
      ? `Игроков проверено: ${body.scannedPlayers ?? 0} · обновлено: ${generated.toLocaleString('ru-RU')}${body.failedEntries ? ` · ошибок чтения: ${body.failedEntries}` : ''}`
      : 'Запусти GitHub Action, чтобы получить данные из Roblox.';
  } catch (error) {
    statusEl.textContent = 'Ошибка загрузки';
    statusEl.classList.add('error');
    rowsEl.innerHTML = '';
    emptyEl.classList.remove('hidden');
    emptyEl.textContent = error.message;
    metaEl.textContent = '';
  }
}

load();
// JSON is regenerated by GitHub Actions. Polling only picks up a fresh deployment if the page stays open.
setInterval(load, 5 * 60_000);
